package need.clarity.mixin;

import need.clarity.render.esp.ShaderEspRenderer;
import net.minecraft.client.renderer.entity.EntityRenderer;
import net.minecraft.client.renderer.entity.state.EntityRenderState;
import net.minecraft.world.entity.Entity;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(EntityRenderer.class)
public abstract class ShaderEspEntityMixin {
   @Inject(method = "extractRenderState(Lnet/minecraft/world/entity/Entity;Lnet/minecraft/client/renderer/entity/state/EntityRenderState;F)V", at = @At("TAIL"))
   private void clarity$shaderEspTag(Entity entity, EntityRenderState state, float partialTick, CallbackInfo ci) {
      ShaderEspRenderer.tagState(entity, state);
   }
}
